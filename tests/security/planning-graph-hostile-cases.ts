/**
 * HOSTILE CASE TABLES for the two planning-graph boundaries on the
 * `scheduler-activation` axis: `ACTIVE_GRAPH_PROJECTION_LAYER` and
 * `GRAPH_BODY_RECORD_LAYER` (coverage task-c5be7926). Both readers entered the
 * tree in commit 9b9e44e; the active-graph one was repaired at d60a48f under
 * task-dd4ffa0c — attributed with `git log --follow`, not from the board.
 *
 * NOT a `*.security.ts` file and it holds NO assertions: the lane collects that
 * suffix, and the slice that imports these tables is where every verdict is
 * reached. This module only ARRANGES durable state and calls production.
 *
 * WHY THESE TWO SIT ON THIS AXIS. Both answer "which planning graph is in force
 * for admission" — the projection decides whether a project HAS a current graph,
 * and the body record decides whether that graph's bytes can be handed back. The
 * digest vocabulary the body record passes through (`GraphContentIssueCode`) is a
 * different subject and is rostered separately as `GRAPH_CONTENT_LAYERS` on the
 * integrity axis.
 *
 * EVERY REVISION HISTORY IS GENERATED BY THE REAL REDUCER. `reduceGraphRevision`
 * emits the events, and only those events are committed. Hand-written event
 * literals are banned here for the same reason the daemon's own suite bans them:
 * nothing writes graph-revision events in production yet, so an authored shape
 * would let both sides drift together while staying green. The command INPUT is
 * restated because `@moe/core`'s revision fixtures pin their own `GRAPH_HASH`,
 * and these fixtures need histories bound to a hash the CODEC actually produced.
 *
 * THE ONE PLANTED ROW, declared rather than hidden: the identity-mismatch arm
 * commits real codec bytes under a DIFFERENT content-hash aggregate. Production
 * is content-addressed, so `putGraphBody` cannot file bytes under a foreign key —
 * which is exactly why the read-side identity check would be unguarded by any
 * fixture that only ever went through the writer. The bytes are the codec's own;
 * only the key they are filed under is hostile.
 */

