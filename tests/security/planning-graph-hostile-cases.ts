export const PLANNING_GRAPH_RACES: readonly HostileRaceCase[] = Object.freeze([
  {
    constant: "ACTIVE_GRAPH_PROJECTION_LAYER",
    // Two ACTIVE revisions is the one condition a current-graph reader exists to detect,
    // and it is committed here from TWO connections to the same durable file. Neither
    // racing reader may resolve it: handing out authority during a split brain is the
    // defect, and "the later one wins" would be a resolution dressed as a read.
    name: "two readers over a split brain committed from two connections both refuse, neither resolves",
    arranged: ACTIVE_GRAPH_PROJECTION_LAYER,
    expected: { code: "ACTIVE_GRAPH_SPLIT_BRAIN", layer: ACTIVE_GRAPH_PROJECTION_LAYER },
    maxAdmitted: 0,
    run: async () => {
      const { store, path } = openPlanningStore("active-graph-race");
      seedActiveRevisionWithBody(store, "graph-revision-1", PRIMARY, "race-primary");
      const rival = openSecondConnection(path);
      seedActiveRevisionWithBody(rival, "graph-revision-2", RIVAL, "race-rival");
      return [
        captureProjection("RACE", readCurrentActiveGraph(store, PROJECT_ID)),
        captureProjection("RACE", readCurrentActiveGraph(rival, PROJECT_ID)),
      ] as const;
    },
  },
  {
    constant: "GRAPH_BODY_RECORD_LAYER",
    // Two connections racing to mint an identity the codec never produced. A returned
    // refusal is not evidence that nothing was written, which is why this race reads the
    // durable row count back: the defect worth catching is a custodian that answers "no"
    // to both callers while a forged body lands anyway.
    name: "two connections racing to write a hand-serialised body are both refused and no row lands",
    arranged: GRAPH_BODY_RECORD_LAYER,
    expected: { code: "GRAPH_BODY_NOT_ENCODED", layer: GRAPH_BODY_RECORD_LAYER },
    maxAdmitted: 0,
    durableAdmissions: forgedDurableAdmissions,
    run: async () => {
      const { store, path } = openPlanningStore("graph-body-race");
      const rival = openSecondConnection(path);
      const forged = forgedContent(PRIMARY);
      const outcomes = [
        captureBody("RACE", putGraphBody(store, PROJECT_ID, forged)),
        captureBody("RACE", putGraphBody(rival, PROJECT_ID, forged)),
      ] as const;
      forgedRowCount = bodyRowCount(store, PRIMARY.graphContentHash);
      return outcomes;
    },
  },
]);

